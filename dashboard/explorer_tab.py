def _num(s):
    return pd.api.types.is_numeric_dtype(s) and not pd.api.types.is_bool_dtype(s)


def apply_filters(df, key, defaults):
    cols = st.multiselect("Filter on these columns", list(df.columns), default=[c for c in defaults if c in df.columns], key=f"{key}_fcols",
                          help="Pick any columns, then narrow each one. Everything below (table, charts, download) follows the filter.")
    mask = pd.Series(True, index=df.index)
    if cols:
        grid = st.columns(min(3, len(cols)))
        for i, c in enumerate(cols):
            s = df[c]
            with grid[i % len(grid)]:
                if pd.api.types.is_datetime64_any_dtype(s):
                    lo, hi = s.min().to_pydatetime(), s.max().to_pydatetime()
                    sel = st.slider(c, lo, hi, (lo, hi), key=f"{key}_f_{c}")
                    mask &= s.between(*sel)
                elif _num(s) and s.nunique() > 12:
                    lo, hi = float(s.min()), float(s.max())
                    if lo == hi:
                        continue
                    sel = st.slider(c, lo, hi, (lo, hi), step=(hi - lo) / 200 if s.dtype.kind == "f" else 1.0, key=f"{key}_f_{c}")
                    mask &= s.between(*sel)
                else:
                    opts = sorted(s.dropna().astype(str).unique())[:300]
                    sel = st.multiselect(c, opts, default=opts, key=f"{key}_f_{c}")
                    mask &= s.astype(str).isin(sel)
    return mask


def profile(df, dic):
    rows = []
    for c in df.columns:
        s = df[c]
        r = {"Column": c, "Type": "number" if _num(s) else ("date" if pd.api.types.is_datetime64_any_dtype(s) else "text"),
             "Missing": int(s.isna().sum()), "Distinct": int(s.nunique())}
        if _num(s):
            r.update({"Lowest": f"{s.min():,.4g}", "Average": f"{s.mean():,.4g}", "Highest": f"{s.max():,.4g}"})
        else:
            top = s.astype(str).value_counts().head(1)
            r.update({"Lowest": "", "Average": "", "Highest": f"most common: {top.index[0]}" if len(top) else ""})
        r["What it is"] = dic.get(c, "")
        rows.append(r)
    return pd.DataFrame(rows)


def split_hist(ctx, df, col, target):
    fig = go.Figure()
    if target and target in df.columns:
        for v, name, colr in ((0, "Repaid", NAVY), (1, "Defaulted", BRICK)):
            fig.add_trace(go.Histogram(x=df.loc[df[target] == v, col], name=name, marker_color=colr, opacity=.62, histnorm="percent", nbinsx=40))
        fig.update_layout(barmode="overlay", yaxis_title="Share of group (%)")
    else:
        fig.add_trace(go.Histogram(x=df[col], marker_color=NAVY, nbinsx=40, name=col))
        fig.update_layout(yaxis_title="Rows")
    fig.update_layout(xaxis_title=col, legend=dict(orientation="h", y=-0.22))
    return ctx.style_fig(fig, 330)


def rate_by(ctx, df, col, target):
    s = df[col]
    if _num(s) and s.nunique() > 12:
        g = pd.qcut(s.rank(method="first"), 10, labels=False)
        lab = df.groupby(g)[col].agg(["min", "max"]).apply(lambda r: f"{r['min']:,.3g} to {r['max']:,.3g}", axis=1)
        key = g.map(lab)
        order = list(lab.values)
    else:
        key = s.astype(str)
        order = None
    t = df.groupby(key, observed=True)[target].agg(["mean", "size"]).rename(columns={"mean": "rate", "size": "n"})
    if order:
        t = t.reindex(order)
    else:
        t = t.sort_values("rate", ascending=False).head(25)
    fig = go.Figure(go.Bar(x=t.index.astype(str), y=t["rate"] * 100, marker_color=NAVY, customdata=t["n"],
                           hovertemplate="%{x}<br>default rate %{y:.1f}%<br>%{customdata:,} rows<extra></extra>"))
    fig.add_hline(y=df[target].mean() * 100, line_dash="dash", line_color=BRICK, annotation_text="overall rate")
    fig.update_layout(xaxis_title=col + (" (10 equal-size groups)" if order else ""), yaxis_title="Default rate (%)")
    fig.update_xaxes(tickangle=-35)
    return ctx.style_fig(fig, 340), t


def render(ctx):
    st.markdown("## Data explorer")
    ctx.explain("Look at the <b>actual data</b> behind every number in the project. Pick a file, narrow it down, and see what it contains, "
                "how its columns are distributed and how they relate to default. Nothing here is typed in: every table is read from the project files.")
    reg = registry(ctx)
    name = st.selectbox("Dataset", list(reg), key="ex_dataset")
    spec = reg[name]
    df = spec["load"]()
    dic_all = dictionary(os.path.join(ctx.DATA_DIR, "data_dictionary.txt"))
    dic = dic_all.get(spec["file"], {}) if spec["file"] else {}
    target = spec["target"] if spec["target"] in df.columns else None
    st.markdown(f'<div class="who custom">{spec["blurb"]}</div>', unsafe_allow_html=True)

    k1, k2, k3, k4 = st.columns(4)
    k1.metric("Rows", f"{len(df):,}")
    k2.metric("Columns", f"{df.shape[1]}")
    k3.metric("Missing cells", f"{int(df.isna().sum().sum()):,}", help="Structural blanks (for example no default month for a loan that never defaulted) are kept on purpose.")
    k4.metric("Default rate" if target else "File", f"{df[target].mean():.2%}" if target else (spec["file"] or "in memory"),
              help="Share of rows where loan_default_status is 1 (90+ days late)." if target else "Source file name.")

    sections = ["Browse and filter", "Column profile", "Relationships"]
    if name.startswith("Monthly transactions"):
        sections.append("Borrower trace")
    if name.startswith(("Portfolio", "Macro")):
        sections.append("Time series")
    sec = st.radio("View", sections, horizontal=True, key=f"ex_sec_{name}", label_visibility="collapsed")

    if sec == "Browse and filter":
        mask = apply_filters(df, f"ex_{name}", spec["filt"])
        sub = df[mask]
        a, b, c = st.columns(3)
        a.metric("Rows after filter", f"{len(sub):,}", delta=f"{len(sub) / max(len(df), 1):.0%} of the file", delta_color="off")
        if target and len(sub):
            b.metric("Default rate in this filter", f"{sub[target].mean():.2%}", delta=f"{(sub[target].mean() - df[target].mean()) * 100:+.2f} pp vs all", delta_color="inverse")
            c.metric("Defaults in this filter", f"{int(sub[target].sum()):,}")
        shown = st.multiselect("Columns to show", list(df.columns), default=list(df.columns)[:10], key=f"ex_cols_{name}")
        st.dataframe(sub[shown].head(2000), width="stretch", height=360, hide_index=True)
        st.caption(f"Showing the first {min(len(sub), 2000):,} of {len(sub):,} rows.")
        st.download_button("Download this filtered view as CSV", sub[shown].head(200000).to_csv(index=False).encode("utf-8"),
                           file_name=f"intellicredit_{re.sub('[^a-z0-9]+', '_', name.lower())[:30]}.csv", mime="text/csv")

    elif sec == "Column profile":
        table(profile(df, dic), widths=[15, 7, 7, 8, 11, 11, 13, 28])
        col = st.selectbox("Look at one column", list(df.columns), key=f"ex_pc_{name}")
        s = df[col]
        if _num(s) and s.nunique() > 2:
            st.plotly_chart(split_hist(ctx, df, col, target), width="stretch", config={"displayModeBar": False})
            if target:
                fig, t = rate_by(ctx, df, col, target)
                st.plotly_chart(fig, width="stretch", config={"displayModeBar": False})
                st.caption("Rows are split into ten equal-size groups from the lowest to the highest value; each bar is that group's default rate.")
        elif target and col != target:
            fig, t = rate_by(ctx, df, col, target)
            st.plotly_chart(fig, width="stretch", config={"displayModeBar": False})
        else:
            vc = df[col].astype(str).value_counts().head(25)
            f = go.Figure(go.Bar(x=vc.index, y=vc.values, marker_color=NAVY))
            f.update_layout(xaxis_title=col, yaxis_title="Rows")
            st.plotly_chart(ctx.style_fig(f, 320), width="stretch", config={"displayModeBar": False})

    elif sec == "Relationships":
        nums = [c for c in df.columns if _num(df[c]) and df[c].nunique() > 2]
        if len(nums) < 2:
            st.info("This file has too few numeric columns for relationship charts.")
        else:
            st.markdown("### Two columns against each other")
            c1, c2 = st.columns(2)
            x = c1.selectbox("Horizontal axis", nums, index=0, key=f"ex_x_{name}")
            y = c2.selectbox("Vertical axis", nums, index=min(1, len(nums) - 1), key=f"ex_y_{name}")
            samp = df.sample(min(4000, len(df)), random_state=7)
            fig = go.Figure()
            if target:
                for v, nm, colr in ((0, "Repaid", NAVY), (1, "Defaulted", BRICK)):
                    d = samp[samp[target] == v]
                    fig.add_trace(go.Scatter(x=d[x], y=d[y], mode="markers", name=nm, marker=dict(size=5, color=colr, opacity=.45 if v == 0 else .8,
                                                                                                    symbol="circle" if v == 0 else "diamond")))
            else:
                fig.add_trace(go.Scatter(x=samp[x], y=samp[y], mode="markers", marker=dict(size=5, color=NAVY, opacity=.5), name="rows"))
            fig.update_layout(xaxis_title=x, yaxis_title=y, legend=dict(orientation="h", y=-0.2))
            st.plotly_chart(ctx.style_fig(fig, 380), width="stretch", config={"displayModeBar": False})
            st.caption(f"A random sample of {len(samp):,} rows. Correlation of the two columns: {df[[x, y]].corr().iloc[0, 1]:+.2f}.")
            st.markdown("### Which columns move together")
            default = [c for c in nums if c != target][:8]
            pick = st.multiselect("Columns in the grid", nums, default=default, key=f"ex_corr_{name}")
            if len(pick) >= 2:
                cm = df[pick].corr()
                h = go.Figure(go.Heatmap(z=cm.values, x=pick, y=pick, zmin=-1, zmax=1, colorscale=[[0, BRICK], [.5, "#fbf8f1"], [1, NAVY]],
                                         text=np.round(cm.values, 2), texttemplate="%{text}", hovertemplate="%{x} and %{y}: %{z:.2f}<extra></extra>"))
                h.update_yaxes(autorange="reversed")
                st.plotly_chart(ctx.style_fig(h, 420), width="stretch", config={"displayModeBar": False})
                st.caption("1 means the two columns rise together, -1 means one rises as the other falls, 0 means no straight-line link.")

    elif sec == "Borrower trace":
        ids = ctx.borrowers["borrower_id"]
        who = st.text_input("Borrower ID", value="BRW-000010", key="ex_bid", help="Try BRW-000010 (a borrower who defaulted) or BRW-000001.")
        one = df[df["borrower_id"] == who.strip().upper()]
        if one.empty:
            st.warning("No borrower with that ID. IDs run from BRW-000001 to BRW-030000.")
        else:
            prof = ctx.borrowers[ctx.borrowers["borrower_id"] == who.strip().upper()].iloc[0]
            st.markdown(f'<div class="who {"no" if prof["loan_default_status"] == 1 else "ok"}"><b>{who.upper()}</b> · {prof["primary_gig_platform"]} · {prof["location_type"]} · '
                        f'{int(prof["gig_tenure_months"])} months on platform · loan Rs {prof["loan_amount_requested"]:,.0f} at {prof["interest_rate_annual"]:.1f}% · '
                        f'<b>{"Defaulted" if prof["loan_default_status"] == 1 else "Repaid"}</b></div>', unsafe_allow_html=True)
            metrics = {"gig_income": "Income (Rs)", "monthly_outflow": "Spending (Rs)", "end_of_month_balance": "End-of-month balance (Rs)",
                       "utility_delay_days": "Utility bill delay (days)", "upi_transaction_count": "UPI payments", "app_login_count": "App logins",
                       "bnpl_total_amount": "Buy-now-pay-later (Rs)"}
            pick = st.multiselect("What to plot", list(metrics), default=["gig_income", "monthly_outflow", "end_of_month_balance"], format_func=lambda k: metrics[k], key="ex_trace")
            fig = go.Figure()
            for i, m in enumerate(pick):
                fig.add_trace(go.Scatter(x=one["month_index"], y=one[m], name=metrics[m], mode="lines+markers", line=dict(color=[NAVY, OCHRE, BRICK, SLATE, "#3d6b4f", "#6b5b7b", "#8a8577"][i % 7]),
                                         marker=dict(symbol=["circle", "square", "diamond", "triangle-up", "x", "cross", "star"][i % 7], size=7)))
            fig.update_layout(xaxis_title="Month of history (1 to 12)", yaxis_title="Value", legend=dict(orientation="h", y=-0.25))
            st.plotly_chart(ctx.style_fig(fig, 360), width="stretch", config={"displayModeBar": False})
            st.dataframe(one.drop(columns=["borrower_id"]), hide_index=True, width="stretch", height=300)
        st.markdown("### Average behaviour of all borrowers by month")
        agg = df.groupby("month_index")[["gig_income", "utility_delay_days", "upi_transaction_count", "app_login_count"]].mean()
        fig2 = go.Figure(go.Scatter(x=agg.index, y=agg["gig_income"], mode="lines+markers", line=dict(color=NAVY), name="Average income"))
        fig2.update_layout(xaxis_title="Month of history", yaxis_title="Average income (Rs)", yaxis_rangemode="tozero")
        st.plotly_chart(ctx.style_fig(fig2, 280), width="stretch", config={"displayModeBar": False})

    elif sec == "Time series":
        nums = [c for c in df.columns if _num(df[c]) and c not in ("covid_lockdown", "covid_second_wave") and not c.endswith("_carried_forward")]
        default = ["default_rate", "dpd30_plus_rate"] if "default_rate" in nums else nums[:2]
        pick = st.multiselect("Series to plot", nums, default=[d for d in default if d in nums], key=f"ex_ts_{name}")
        fig = go.Figure()
        for i, m in enumerate(pick):
            fig.add_trace(go.Scatter(x=df["date"], y=df[m], name=m, mode="lines", line=dict(color=[NAVY, OCHRE, BRICK, SLATE][i % 4], width=2.2,
                                                                                               dash=["solid", "dash", "dot", "dashdot"][i % 4])))
        if "covid_lockdown" in df.columns:
            for col_, lab in (("covid_lockdown", "Lockdown"), ("covid_second_wave", "Second wave")):
                on = df.loc[df[col_] == 1, "date"]
                if len(on):
                    fig.add_vrect(x0=on.min(), x1=on.max() + pd.offsets.MonthEnd(0), fillcolor="rgba(138,133,119,.18)", line_width=0, annotation_text=lab, annotation_position="top left")
        fig.update_layout(legend=dict(orientation="h", y=-0.2), yaxis_title="Value (scales differ: pick series with similar units)")
