@st.cache_data(show_spinner="Reading the file ...")
def read_csv(path, dates=None):
    return pd.read_csv(path, parse_dates=dates or [])


@st.cache_data
def dictionary(path):
    out, cur = {}, None
    if not os.path.exists(path):
        return out
    for line in open(path, encoding="utf-8"):
        m = re.match(r"^FILE:\s*(\S+)", line)
        if m:
            cur = m.group(1)
            out[cur] = {}
            continue
        m = re.match(r"^\s{2}(\w+)\s*:\s*(.+)$", line)
        if m and cur:
            out[cur][m.group(1)] = m.group(2).strip()
    return out


